import { expect, test } from '../fixtures/test.fixtures';
import { CategoryKind } from '../../src/app/enums/category-kind.enum';
import { ErrorCode } from '../../src/app/enums/error-code.enum';
import { HttpRequestMethod } from '../../src/app/enums/http-request-method.enum';
import en from '../../src/app/i18n/en.json';
import { LOVED_CATEGORY, SHORT_CATEGORY } from '../constants/test-data.constants';
import { deleteCategories, saveCategories } from '../helpers/api.helpers';
import { getGameFormButton, getGameNameInput, selectOption } from '../helpers/game-form.helpers';
import { getConfirmationButton, getConfirmationDialog, getSnackbar, openMainPage, reloadMainPage } from '../helpers/main-page.helpers';
import { waitForApiResponse } from '../helpers/network.helpers';
import {
    chooseWallpaperFile,
    expandWallpaper,
    getAutoGenerateCheckbox,
    getClearExcludedCategoryButton,
    getDesktopUpdateCheckbox,
    getExcludedCategorySelect,
    getPreviewCaption,
    getPreviewImage,
    getWallpaperButton,
    getWallpaperRegion,
    holdWallpaperGeneration,
    mockApiResponse,
    mockWallpaper,
    mockWallpaperPng,
} from '../helpers/wallpaper.helpers';

const xcfFile = { name: 'wallpaper.xcf', mimeType: 'image/x-xcf', buffer: Buffer.from('gimp xcf v011') };

test.describe('Wallpaper', () => {
    test.beforeEach(async ({ page, request }) => {
        await saveCategories(request, CategoryKind.MAIN, [LOVED_CATEGORY]);
        await saveCategories(request, CategoryKind.LENGTH, [SHORT_CATEGORY]);
        // The section works the same whether GIMP is installed on the machine running the tests or not
        await mockWallpaper(page, { isGimpInstalled: true });
    });

    test.afterEach(async ({ request }) => {
        await deleteCategories(request, [CategoryKind.MAIN, CategoryKind.LENGTH]);
    });

    test.describe('settings', () => {
        test('should save the category left out of the number in brackets', async ({ page }) => {
            await openMainPage(page);
            await expandWallpaper(page);

            const saveResponsePromise = waitForApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/settings');

            await selectOption(page, getExcludedCategorySelect(page), SHORT_CATEGORY.name);

            const saveResponse = await saveResponsePromise;

            expect(saveResponse.ok()).toBe(true);
            await expect(getSnackbar(page, en.manageWallpaper.settingsSuccess)).toBeVisible();
            await expect(getExcludedCategorySelect(page)).toHaveText(SHORT_CATEGORY.name);

            await test.step('keeps the category after reload', async () => {
                await reloadMainPage(page);
                await expandWallpaper(page);

                await expect(getExcludedCategorySelect(page)).toHaveText(SHORT_CATEGORY.name);
            });

            await test.step('stops leaving the category out after clearing it', async () => {
                const clearResponsePromise = waitForApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/settings');

                await getClearExcludedCategoryButton(page).click();

                const clearResponse = await clearResponsePromise;

                expect(clearResponse.ok()).toBe(true);
                expect(clearResponse.request().postDataJSON()).toMatchObject({ excludedCategoryId: null });
                await expect(getExcludedCategorySelect(page)).not.toHaveText(SHORT_CATEGORY.name);
                await expect(getClearExcludedCategoryButton(page)).toBeHidden();
            });
        });

        test('should allow generating by hand only once the automatic generation is turned off', async ({ page }) => {
            await mockWallpaper(page, { isGimpInstalled: true, isAutoGenerateEnabled: true }, 1);
            await openMainPage(page);
            await expandWallpaper(page);

            await expect(getAutoGenerateCheckbox(page)).toBeChecked();
            await expect(getWallpaperButton(page, 'Generate')).toBeDisabled();
            await expect(getWallpaperButton(page, 'Generate')).toHaveAccessibleDescription(en.manageWallpaper.autoGenerated);

            const saveResponsePromise = waitForApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/settings');

            await getAutoGenerateCheckbox(page).uncheck();

            const saveResponse = await saveResponsePromise;

            expect(saveResponse.ok()).toBe(true);
            expect(saveResponse.request().postDataJSON()).toMatchObject({ isAutoGenerateEnabled: false });
            await expect(getSnackbar(page, en.manageWallpaper.settingsSuccess)).toBeVisible();
            await expect(getAutoGenerateCheckbox(page)).not.toBeChecked();
            await expect(getWallpaperButton(page, 'Generate')).toBeEnabled();
        });

        test('should not allow updating the desktop wallpaper outside production', async ({ page }) => {
            await openMainPage(page);
            await expandWallpaper(page);

            await expect(getDesktopUpdateCheckbox(page)).toBeDisabled();
            await expect(getDesktopUpdateCheckbox(page)).toHaveAccessibleDescription(en.manageWallpaper.desktopUnavailable);
        });
    });

    test('should generate the wallpaper by hand and download it', async ({ page }) => {
        await mockWallpaper(page, { isGimpInstalled: true, text: '2 (1)', png: { width: 1920, height: 1080, size: 30_000, modifiedAt: Date.now() } });
        await mockWallpaper(page, { isGimpInstalled: true, text: null, png: null }, 1);
        await mockWallpaperPng(page);
        await mockApiResponse(page, HttpRequestMethod.POST, 'wallpaper/generate');
        await openMainPage(page);
        await expandWallpaper(page);

        await expect(getWallpaperRegion(page).getByText(en.manageWallpaper.noPreview)).toBeVisible();
        await expect(getWallpaperButton(page, 'Download')).toBeDisabled();

        const generateResponsePromise = waitForApiResponse(page, HttpRequestMethod.POST, 'wallpaper/generate');

        await getWallpaperButton(page, 'Generate').click();

        const generateResponse = await generateResponsePromise;

        expect(generateResponse.ok()).toBe(true);
        await expect(getSnackbar(page, en.manageWallpaper.generateSuccess)).toBeVisible();
        await expect(getPreviewImage(page, '2 (1)')).toBeVisible();
        await expect(getPreviewCaption(page, '2 (1)')).toBeVisible();
        await expect(getWallpaperRegion(page).getByText('1920 × 1080 px, 29 KB')).toBeVisible();

        await test.step('downloads the generated PNG', async () => {
            const downloadPromise = page.waitForEvent('download');

            await getWallpaperButton(page, 'Download').click();

            const download = await downloadPromise;

            expect(download.suggestedFilename()).toBe('wallpaper.png');
        });
    });

    test.describe('uploading', () => {
        test.beforeEach(async ({ page }) => {
            await openMainPage(page);
            await expandWallpaper(page);
        });

        test('should reject a file which is not an XCF without uploading it', async ({ page }) => {
            const uploadRequests: string[] = [];

            page.on('request', (uploadRequest) => {
                if (uploadRequest.url().endsWith('/api/wallpaper/xcf')) {
                    uploadRequests.push(uploadRequest.url());
                }
            });

            await chooseWallpaperFile(page, { name: 'wallpaper.png', mimeType: 'image/png', buffer: Buffer.from('png') });

            await expect(getSnackbar(page, en.manageWallpaper.invalidFile)).toBeVisible();
            expect(uploadRequests).toEqual([]);
        });

        test('should inform about the file rejected by the backend for not being an XCF', async ({ page }) => {
            const uploadResponsePromise = waitForApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/xcf');

            await chooseWallpaperFile(page, { ...xcfFile, buffer: Buffer.from('not an xcf') });

            const uploadResponse = await uploadResponsePromise;

            expect(uploadResponse.status()).toBe(400);
            await expect(getSnackbar(page, en.manageWallpaper.invalidFile)).toBeVisible();
        });

        test('should upload the XCF file', async ({ page }) => {
            await mockApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/xcf');

            const uploadResponsePromise = waitForApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/xcf');

            await chooseWallpaperFile(page, xcfFile);

            const uploadResponse = await uploadResponsePromise;

            expect(uploadResponse.ok()).toBe(true);
            await expect(getSnackbar(page, en.manageWallpaper.uploadSuccess)).toBeVisible();
        });

        test('should inform about the XCF file without exactly one text layer', async ({ page }) => {
            await mockApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/xcf', 400, {
                message: 'The XCF file has to have exactly 1 text layer, but it has 2',
                errorCode: ErrorCode.INVALID_WALLPAPER_TEXT_LAYERS,
                statusCode: 400,
            });

            const uploadResponsePromise = waitForApiResponse(page, HttpRequestMethod.PUT, 'wallpaper/xcf');

            await chooseWallpaperFile(page, xcfFile);

            const uploadResponse = await uploadResponsePromise;

            expect(uploadResponse.status()).toBe(400);
            await expect(getSnackbar(page, en.manageWallpaper.invalidTextLayers)).toBeVisible();
        });
    });

    test('should restore the default wallpaper only after confirmation', async ({ page }) => {
        const restoreRequests: string[] = [];

        page.on('request', (restoreRequest) => {
            if (restoreRequest.url().endsWith('/api/wallpaper/restore')) {
                restoreRequests.push(restoreRequest.url());
            }
        });
        await mockApiResponse(page, HttpRequestMethod.POST, 'wallpaper/restore');
        await openMainPage(page);
        await expandWallpaper(page);

        await getWallpaperButton(page, 'Restore default wallpaper').click();
        await expect(getConfirmationDialog(page)).toContainText(`${en.confirmation.restoreWallpaper.questionStart} ${en.confirmation.restoreWallpaper.identifier}`);
        await getConfirmationButton(page, 'No').click();

        await expect(getConfirmationDialog(page)).toBeHidden();
        expect(restoreRequests).toEqual([]);

        await test.step('restores the wallpaper once confirmed', async () => {
            await getWallpaperButton(page, 'Restore default wallpaper').click();

            const restoreResponsePromise = waitForApiResponse(page, HttpRequestMethod.POST, 'wallpaper/restore');

            await getConfirmationButton(page, 'Yes').click();

            const restoreResponse = await restoreResponsePromise;

            expect(restoreResponse.ok()).toBe(true);
            await expect(getSnackbar(page, en.manageWallpaper.restoreSuccess)).toBeVisible();
        });
    });

    test('should warn and allow nothing but downloading when GIMP is not installed', async ({ page }) => {
        await mockWallpaper(page, { isGimpInstalled: false });
        await openMainPage(page);
        await expandWallpaper(page);

        await expect(getWallpaperRegion(page).getByText(en.manageWallpaper.warnbar)).toBeVisible();
        await expect(getWallpaperRegion(page).getByText(en.manageWallpaper.infobar)).toBeHidden();
        await expect(getWallpaperButton(page, 'Choose XCF file')).toBeDisabled();
        await expect(getWallpaperButton(page, 'Restore default wallpaper')).toBeDisabled();
        await expect(getWallpaperButton(page, 'Generate')).toBeDisabled();
        await expect(getExcludedCategorySelect(page)).toBeDisabled();
        await expect(getAutoGenerateCheckbox(page)).toBeDisabled();
    });

    test.describe('while the wallpaper is generated', () => {
        test('should not allow adding a game until the wallpaper is generated', async ({ page }) => {
            const finishGeneration = await holdWallpaperGeneration(page);

            await openMainPage(page);
            await getGameNameInput(page).fill('Portal');
            await expect(getGameFormButton(page, 'Add game')).toBeEnabled();
            await expandWallpaper(page);

            const generateResponsePromise = waitForApiResponse(page, HttpRequestMethod.POST, 'wallpaper/generate');

            await getWallpaperButton(page, 'Generate').click();

            await expect(getWallpaperRegion(page).getByRole('button', { name: en.manageWallpaper.generating })).toBeDisabled();
            await expect(getGameFormButton(page, 'Add game')).toBeDisabled();
            await expect(getGameFormButton(page, 'Add game')).toHaveAccessibleDescription(en.common.wallpaperGenerating);

            finishGeneration();

            const generateResponse = await generateResponsePromise;

            expect(generateResponse.ok()).toBe(true);
            await expect(getSnackbar(page, en.manageWallpaper.generateSuccess)).toBeVisible();
            await expect(getGameFormButton(page, 'Add game')).toBeEnabled();
        });

        test('should inform about the game rejected by the backend while generating in the background', async ({ page }) => {
            await mockApiResponse(page, HttpRequestMethod.POST, 'game', 409, {
                message: 'The wallpaper is being generated, try again once it is done',
                errorCode: ErrorCode.WALLPAPER_GENERATING,
                statusCode: 409,
            });
            await openMainPage(page);
            await getGameNameInput(page).fill('Portal');

            const addResponsePromise = waitForApiResponse(page, HttpRequestMethod.POST, 'game');

            await getGameFormButton(page, 'Add game').click();

            const addResponse = await addResponsePromise;

            expect(addResponse.status()).toBe(409);
            await expect(getSnackbar(page, en.common.wallpaperGenerating)).toBeVisible();
            await expect(getGameNameInput(page)).toHaveValue('Portal');
        });
    });
});
