import { computed, Injectable, inject, signal } from '@angular/core';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';

import { catchError, concat, of, Subject, switchMap } from 'rxjs';

import { WallpaperApiService } from './wallpaper-api.service';
import type { Wallpaper } from '../../../interfaces/wallpaper.interface';

@Injectable()
export class WallpaperStatusService {
    private readonly wallpaperApiService = inject(WallpaperApiService);

    private readonly statusRefreshes = new Subject<void>();
    private readonly latestWallpaper = signal<Wallpaper | null>(null);
    public readonly wallpaper = this.latestWallpaper.asReadonly();

    // Generated by a request of the Manage wallpaper section, which the backend reports only once it's done
    private readonly isGeneratingInSection = signal<boolean>(false);

    public readonly isGenerating = computed<boolean>(() => this.isGeneratingInSection() || (this.latestWallpaper()?.isGenerating ?? false));

    constructor() {
        this.statusRefreshes
            .pipe(
                switchMap(() =>
                    this.wallpaperApiService.getWallpaper().pipe(
                        // While the wallpaper is updated in the background, its status is followed by the one the backend answers with once it's generated
                        switchMap((wallpaper) => (wallpaper.isUpdating ? concat(of(wallpaper), this.wallpaperApiService.waitForUpdate()) : of(wallpaper))),
                        // An unknown status doesn't block changing games, groups and categories, which the backend still rejects while generating
                        catchError(() => of(null))
                    )
                ),
                takeUntilDestroyed()
            )
            .subscribe((wallpaper) => this.latestWallpaper.set(wallpaper));
    }

    public refreshStatus(): void {
        this.statusRefreshes.next();
    }

    public setGeneratingInSection(isGenerating: boolean): void {
        this.isGeneratingInSection.set(isGenerating);
    }
}
