import type { DataSource } from 'typeorm';

import { Category } from '../../src/entities/category.entity';
import { Game } from '../../src/entities/game.entity';
import { GameGroup } from '../../src/entities/game-group.entity';
import { CategoryKind } from '../../src/enums/category-kind.enum';
import { seedOneHundredPercentCategory } from '../../src/seeds/one-hundred-percent-category.seed';
import { buildCategory } from '../../src/testing/builders/category.builders';
import { buildGame, buildGameGroup } from '../../src/testing/builders/game.builders';

// Empties every table, including the join table of games and categories, and creates the 100% category like on application start
export const resetDatabase = async (dataSource: DataSource): Promise<void> => {
    const tables = dataSource.entityMetadatas.map(({ tablePath }) => `"${tablePath}"`).join(', ');

    await dataSource.query(`TRUNCATE ${tables} RESTART IDENTITY CASCADE`);
    await seedOneHundredPercentCategory(dataSource);
};

export const getOneHundredPercentCategory = (dataSource: DataSource): Promise<Category> => dataSource.getRepository(Category).findOneByOrFail({ kind: CategoryKind.ONE_HUNDRED_PERCENT });

// Ids are generated by the database, so the ids of the builders are never saved
export const insertCategory = (dataSource: DataSource, overrides: Partial<Category> = {}): Promise<Category> => dataSource.getRepository(Category).save(buildCategory({ id: undefined, ...overrides }));

export const insertGame = async (dataSource: DataSource, overrides: Partial<Game> = {}, groups: Partial<GameGroup>[] = []): Promise<Game> => {
    const game = await dataSource.getRepository(Game).save(buildGame({ id: undefined, ...overrides }));
    const savedGroups = await dataSource.getRepository(GameGroup).save(groups.map((group) => buildGameGroup({ id: undefined, ...group, game })));

    return Object.assign(game, { groups: savedGroups.map(({ id, name, hasNewAchievements }) => buildGameGroup({ id, name, hasNewAchievements })) });
};

// Categories and groups of every game are ordered, so whole games can be compared
export const findGames = (dataSource: DataSource): Promise<Game[]> =>
    dataSource.getRepository(Game).find({ relations: { categories: true, groups: true }, order: { id: 'ASC', categories: { id: 'ASC' }, groups: { id: 'ASC' } } });

export const findCategories = (dataSource: DataSource, kind: CategoryKind): Promise<Category[]> => dataSource.getRepository(Category).find({ where: { kind }, order: { position: 'ASC' } });
